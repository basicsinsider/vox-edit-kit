"""Geo data for the Russia -> Saint Petersburg map scene (x01): country outline, city urban area, Neva river,
in the pixel spaces of the three relief maps made by gen_relief.py with --xscale 0.5.
  wide   russia_relief_grey.jpg        lon 10..185 lat 28..84   ppd 60  (x = (lon-10)*30,    y = (84-lat)*60)
  mid    gulf_finland_relief_grey.jpg  lon 20..42  lat 56..64   ppd 300 (x = (lon-20)*150,   y = (64-lat)*300)
  detail spb_relief_grey.jpg           lon 28.6..32.2 lat 59.45..60.35 ppd 2000 (x = (lon-28.6)*1000, y = (60.35-lat)*2000)
Usage: python3 tools/gen_russia_spb_geo.py <natural-earth geojson dir> assets/maps/russia/russia_spb.json
Data: Natural Earth (public domain) — ne_50m_admin_0_countries, ne_10m_urban_areas, ne_10m_rivers_lake_centerlines."""
import json, sys

src, out = sys.argv[1], sys.argv[2]
WIDE = dict(lon0=10, lat1=84, ppd=60, k=0.5)
DET = dict(lon0=28.6, lat1=60.35, ppd=2000, k=0.5)


def proj(m, lon, lat):
    return ((lon - m["lon0"]) * m["ppd"] * m["k"], (m["lat1"] - lat) * m["ppd"])


def simplify(pts, tol):
    # radial-distance simplification (good enough for display paths)
    o = [pts[0]]
    for p in pts[1:]:
        if (p[0] - o[-1][0]) ** 2 + (p[1] - o[-1][1]) ** 2 >= tol * tol:
            o.append(p)
    return o


def path(rings, m, tol, shift=None):
    s = []
    for r in rings:
        pts = [proj(m, (x + 360 if shift and x < 0 else x), y) for x, y in r]
        pts = simplify(pts, tol)
        if len(pts) < 3:
            continue
        s.append("M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in pts) + "Z")
    return "".join(s)


def polys(g):
    return g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]


countries = json.load(open(f"{src}/ne_50m_admin_0_countries.geojson"))["features"]
rus = next(f for f in countries if f["properties"].get("ADM0_A3") == "RUS")
rus_rings = [p[0] for p in polys(rus["geometry"])]
rus_d = path(rus_rings, WIDE, 1.5, shift=True)

urban = json.load(open(f"{src}/ne_10m_urban_areas.geojson"))["features"]
spb = (30.3086, 59.9375)
best = None
for f in urban:
    for p in polys(f["geometry"]):
        xs = [c[0] for c in p[0]]; ys = [c[1] for c in p[0]]
        if min(xs) <= spb[0] <= max(xs) and min(ys) <= spb[1] <= max(ys):
            area = (max(xs) - min(xs)) * (max(ys) - min(ys))
            if not best or area > best[0]:
                best = (area, p[0])
urban_pts = [proj(DET, x, y) for x, y in best[1]]
urban_d = "M" + " L".join(f"{x:.1f},{y:.1f}" for x, y in urban_pts) + "Z"
ux = [p[0] for p in urban_pts]; uy = [p[1] for p in urban_pts]

rivers = json.load(open(f"{src}/ne_10m_rivers_lake_centerlines.geojson"))["features"]
neva = []
for f in rivers:
    if (f["properties"].get("name") or "") == "Neva":
        g = f["geometry"]
        lines = g["coordinates"] if g["type"] == "MultiLineString" else [g["coordinates"]]
        for ln in lines:
            neva.append("M" + " L".join("%.1f,%.1f" % proj(DET, x, y) for x, y in ln))

cx, cy = proj(DET, *spb)
wx, wy = proj(WIDE, *spb)
json.dump({
    "note": "generated by tools/gen_russia_spb_geo.py (Natural Earth, public domain)",
    "wide": {"image": "assets/maps/russia/russia_relief_grey.jpg", "w": 5250, "h": 3360, **WIDE},
    "mid": {"image": "assets/maps/russia/gulf_finland_relief_grey.jpg", "w": 3300, "h": 2400, "lon0": 20, "lat1": 64, "ppd": 300, "k": 0.5,
            "in_wide": {"left": (20 - 10) * 30, "top": (84 - 64) * 60, "scale": 60 / 300}},
    "detail": {"image": "assets/maps/russia/spb_relief_grey.jpg", "w": 3600, "h": 1800, **DET,
               "in_wide": {"left": (28.6 - 10) * 30, "top": (84 - 60.35) * 60, "scale": 60 / 2000}},
    "russia_d": rus_d,
    "spb_wide": [round(wx, 1), round(wy, 1)],
    "spb_detail": [round(cx, 1), round(cy, 1)],
    "urban_d": urban_d,
    "urban_bbox": [round(min(ux)), round(min(uy)), round(max(ux)), round(max(uy))],
    "neva_d": "".join(neva),
}, open(out, "w"))
print(out, "russia path", len(rus_d), "urban bbox", [round(min(ux)), round(min(uy)), round(max(ux)), round(max(uy))], "neva", len(neva))
