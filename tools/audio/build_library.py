import sys

import numpy as np
import soundfile as sf

sys.path.insert(0, os.path.dirname(__file__))
from dsp import AUDIO, ROOT
from loudness import integrated_lufs

MAN = os.path.join(ROOT, "tools", "audio", "_manifests")


def stats(rel):
    x, sr = sf.read(os.path.join(AUDIO, rel), always_2d=True)
    return len(x) / sr, x.shape[1], 20 * np.log10(np.abs(x).max() + 1e-12), integrated_lufs(x, sr)


def hit(rel):
    """Onset (first sample within 10 dB of peak) and loudest 10 ms window, in seconds."""
    x, sr = sf.read(os.path.join(AUDIO, rel), always_2d=True)
    a = np.abs(x).max(1)
    on = np.argmax(a > a.max() * 10 ** (-10 / 20)) / sr
    w = int(0.01 * sr)
    e = np.convolve(a ** 2, np.ones(w), "same")
    return on, np.argmax(e) / sr


def table(items, sync=False):
    h = "| File | Dur (s) | Ch | Peak dBFS | LUFS-I |" + (" Onset / loudest @ s |" if sync else "") + " What it's for |"
    out = [h, "|---|---:|:-:|---:|---:|" + ("---:|" if sync else "") + "---|"]
    for it in items:
        d, ch, pk, lu = stats(it["file"])
        sy = ""
        if sync:
            on, mx = hit(it["file"])
            sy = " — |" if "loop" in it["file"] else f" {on:.3f} / {mx:.3f} |"
        out.append(f"| `{it['file']}` | {d:.2f} | {'st' if ch == 2 else 'mono'} | {pk:.1f} | {lu:.1f} |{sy} {it['purpose']} |")
    return "\n".join(out)


