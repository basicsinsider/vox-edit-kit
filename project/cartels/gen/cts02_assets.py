import re, os, json, subprocess, sys
sys.setrecursionlimit(20000)
import numpy as np
from PIL import Image
Image.MAX_IMAGE_PIXELS = None
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
K = f"{ROOT}/assets/maps/kit"
OUT = f"{ROOT}/assets/cartels/cts02/derived"
os.makedirs(OUT, exist_ok=True)


def rdp(pts, eps):
    if len(pts) < 3:
        return pts
    a, b = np.array(pts[0]), np.array(pts[-1])
    d = b - a
    n = np.hypot(*d)
    P = np.array(pts)
    dist = np.abs(d[0] * (P[:, 1] - a[1]) - d[1] * (P[:, 0] - a[0])) / n if n > 0 else np.hypot(*(P - a).T)
    i = int(np.argmax(dist))
    if dist[i] > eps:
        return rdp(pts[: i + 1], eps)[:-1] + rdp(pts[i:], eps)
    return [pts[0], pts[-1]]


def subpaths(d):
    out = []
    for sp in re.split(r"(?=M)", d):
        nums = list(map(float, re.findall(r"-?\d+(?:\.\d+)?", sp)))
        if len(nums) >= 4:
            out.append(list(zip(nums[0::2], nums[1::2])))
    return out


def simplify(d, eps, dx=0.0, dy=0.0, minlen=6, bbox=None, jump=True):
    res = []
    for pts in subpaths(d):
        pts = [(x - dx, y - dy) for x, y in pts]
        if bbox:
            xs, ys = [p[0] for p in pts], [p[1] for p in pts]
            if max(xs) < bbox[0] or min(xs) > bbox[2] or max(ys) < bbox[1] or min(ys) > bbox[3]:
                continue
        # drop antimeridian jumps
        if jump and any(abs(pts[i + 1][0] - pts[i][0]) > 400 for i in range(len(pts) - 1)):
            continue
        h = len(pts) // 2
        s = rdp(pts[: h + 1], eps)[:-1] + rdp(pts[h:], eps)
        if len(s) < 3:
            continue
        xs, ys = [p[0] for p in s], [p[1] for p in s]
        if max(xs) - min(xs) < minlen and max(ys) - min(ys) < minlen:
            continue
        res.append("M" + "L".join(f"{x:.0f},{y:.0f}" for x, y in s) + "Z")
    return "".join(res)


def get(svg, i):
    m = re.search(r'id="' + re.escape(i) + r'"[^>]*?\sd="([^"]*)"', svg)
    return m.group(1) if m else ""


paths = {}
# ---- sinaloa kit ----
s = open(f"{K}/sinaloa_overlay.svg").read()
for k in ["st-sinaloa", "rg-northern_sinaloa", "st-chihuahua", "st-durango", "c-mexico"]:
    paths["SIN_" + k.replace("-", "_")] = simplify(get(s, k), 2.2, minlen=(400 if k in ("st-sinaloa", "rg-northern_sinaloa") else 6), jump=False)
# ---- caribbean crop of americas_night ----
X0, Y0, W, H = 909.8, 364.0, 2958, 2048   # in americas_night px
am = Image.open(f"{K}/americas_night.jpg")
am.crop((round(X0), round(Y0), round(X0) + W, round(Y0) + H)).save(f"{OUT}/caribbean_night.jpg", quality=90)
wo = open(f"{K}/world_overlay.svg").read()
dx, dy = 2276 + X0, 1593 + Y0   # world px of the crop origin
cg = wo[wo.find('<g id="countries"'):]
cg = cg[: cg.find("</g>")]
borders = []
for m in re.finditer(r'id="(c-[^"]+)"[^>]*?\sd="([^"]*)"', cg):
    sp = simplify(m.group(2), 1.6, dx, dy, minlen=10, bbox=(-50, -50, W + 50, H + 50))
    if sp:
        borders.append(sp)
        if m.group(1) in ("c-united_states_of_america", "c-venezuela", "c-mexico"):
            paths["CAR_" + m.group(1)[2:]] = sp
paths["CAR_borders"] = "".join(borders)
for k, v in paths.items():
    print(k, len(v))
# ---- board prints (stills from shared footage) ----
F = f"{ROOT}/assets/cartels/footage"
for src, t, name in [("x_chihuahua_narcolab_a", 6.0, "print_narcolab"), ("x_boat_strike_secwar", 2.0, "print_boat"),
                     ("x_maduro_stairs_stewart", 5.0, "print_maduro")]:
    subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-ss", str(t), "-i", f"{F}/{src}.mp4", "-frames:v", "1", "-q:v", "3",
                    f"{OUT}/{name}.jpg"], check=True)
# ---- inline into the composition ----
comp = f"{ROOT}/compositions/cts02.html"
if os.path.exists(comp):
    c = open(comp).read()
    a, b = c.find("// @@PATHS-BEGIN"), c.find("// @@PATHS-END")
    if a >= 0 and b > a:
        js = "// @@PATHS-BEGIN (generated by project/cartels/gen/cts02_assets.py)\n    const MAP = " + json.dumps(paths) + ";\n    "
        c = c[:a] + js + c[b:]
        open(comp, "w").write(c)
        print("inlined paths into", comp)
